/* =========================================================
   HABIT DRAFT

   Хранит временные данные новой привычки,
   пока пользователь ещё не нажал «Сохранить».
   ========================================================= */


/* =========================================================
   ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ
   ========================================================= */

const DEFAULT_HABIT_DRAFT = {
    name: "",
    icon: "✱",
    color: "blue",
    size: "large"
}


/* =========================================================
   ТЕКУЩИЙ ЧЕРНОВИК
   ========================================================= */

const habitDraft = {
    ...DEFAULT_HABIT_DRAFT
}


/* =========================================================
   ПОЛУЧИТЬ ЧЕРНОВИК
   ========================================================= */

export function getHabitDraft() {
    return {
        ...habitDraft
    }
}


/* =========================================================
   ПОЛУЧИТЬ ОТДЕЛЬНОЕ ЗНАЧЕНИЕ
   ========================================================= */

export function getHabitDraftValue(key) {
    return habitDraft[key]
}


/* =========================================================
   ИЗМЕНИТЬ ОДНО ПОЛЕ
   ========================================================= */

export function setHabitDraftValue(key, value) {
    if (!(key in DEFAULT_HABIT_DRAFT)) {
        console.warn(
            `Habit Draft: неизвестное поле "${key}"`
        )

        return
    }

    habitDraft[key] = value
}


/* =========================================================
   ОБНОВИТЬ НЕСКОЛЬКО ПОЛЕЙ
   ========================================================= */

export function updateHabitDraft(values = {}) {
    Object.keys(DEFAULT_HABIT_DRAFT).forEach((key) => {
        if (key in values) {
            habitDraft[key] = values[key]
        }
    })
}


/* =========================================================
   СБРОСИТЬ ЧЕРНОВИК
   ========================================================= */

export function resetHabitDraft() {
    Object.assign(
        habitDraft,
        DEFAULT_HABIT_DRAFT
    )
}